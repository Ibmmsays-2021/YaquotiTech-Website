// Post-build step (run by `npm run build`). Reads the prerendered output and writes:
//   sitemap.xml                – every indexable page (the site is English only)
//   robots.txt                 – points crawlers at the sitemap
//   staticwebapp.config.json   – Azure Static Web Apps: 301s for old URLs (incl. the retired /ar site) + 404 page
//   web.config                 – IIS: the same 301s (URL Rewrite module) + 404 page
// Redirects come from the redirect pages Angular prerendered for the routes in app.routes.ts,
// so the list is never maintained twice.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist', 'yaquoti-tech');
const browser = join(out, 'browser');

const origin = readFileSync(join(root, 'src/app/core/config.ts'), 'utf8').match(
  /SITE_ORIGIN = '([^']+)'/,
)?.[1];
if (!origin) throw new Error('SITE_ORIGIN not found in src/app/core/config.ts');

const { routes } = JSON.parse(readFileSync(join(out, 'prerendered-routes.json'), 'utf8'));
const unescape = (s) => s.replace(/&amp;/g, '&');

const pages = [];
const redirects = [];
for (const route of Object.keys(routes)) {
  const file = join(browser, route, 'index.html');
  if (!existsSync(file)) continue;
  const html = readFileSync(file, 'utf8');
  const refresh = html.match(/http-equiv="refresh" content="0; url=([^"]+)"/);
  if (refresh) redirects.push({ from: route, to: unescape(refresh[1]) });
  else if (!/name="robots" content="noindex"/.test(html) && route !== '/') pages.push(route);
}

// ---- sitemap.xml ----
const today = new Date().toISOString().slice(0, 10);
const entries = pages
  .sort()
  .map((r) => `  <url>\n    <loc>${origin}${r}</loc>\n    <lastmod>${today}</lastmod>\n  </url>`)
  .join('\n');
writeFileSync(
  join(browser, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${entries}\n</urlset>\n`,
);

// ---- robots.txt ----
writeFileSync(
  join(browser, 'robots.txt'),
  `User-agent: *\nAllow: /\n\nSitemap: ${origin}/sitemap.xml\n`,
);

// ---- Azure Static Web Apps ----
const swa = {
  routes: [
    ...redirects.flatMap(({ from, to }) => [
      { route: from, redirect: to, statusCode: 301 },
      { route: `${from}/index.html`, redirect: to, statusCode: 301 },
    ]),
    // The retired Arabic site. SWA can't carry the path over, so these land on the English home;
    // the app itself maps /ar/<page> to /en/<page> for links followed inside the browser.
    { route: '/ar', redirect: '/en', statusCode: 301 },
    { route: '/ar/*', redirect: '/en', statusCode: 301 },
  ],
  responseOverrides: { 404: { rewrite: '/en/not-found/index.html', statusCode: 404 } },
  globalHeaders: {
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
  },
  mimeTypes: { '.woff2': 'font/woff2' },
};
writeFileSync(join(browser, 'staticwebapp.config.json'), JSON.stringify(swa, null, 2) + '\n');

// ---- IIS ----
const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
const rules = redirects
  .map(
    ({ from, to }, i) => `        <rule name="legacy-${i}" stopProcessing="true">
          <match url="^${esc(from.slice(1).replace(/[.]/g, '\\.'))}(/|/index\\.html)?$" />
          <action type="Redirect" url="${esc(to)}" appendQueryString="false" redirectType="Permanent" />
        </rule>`,
  )
  .concat(`        <rule name="retired-arabic-site" stopProcessing="true">
          <match url="^ar(/.*)?$" />
          <action type="Redirect" url="/en{R:1}" appendQueryString="true" redirectType="Permanent" />
        </rule>`)
  .join('\n');
writeFileSync(
  join(browser, 'web.config'),
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/sitemap.mjs. Requires the IIS URL Rewrite module for the redirects. -->
<configuration>
  <system.webServer>
    <staticContent>
      <remove fileExtension=".woff2" />
      <mimeMap fileExtension=".woff2" mimeType="font/woff2" />
    </staticContent>
    <rewrite>
      <rules>
${rules}
      </rules>
    </rewrite>
    <httpErrors errorMode="Custom" existingResponse="Replace">
      <remove statusCode="404" />
      <error statusCode="404" path="/en/not-found/index.html" responseMode="ExecuteURL" />
    </httpErrors>
  </system.webServer>
</configuration>
`,
);

console.log(
  `sitemap.xml: ${pages.length} pages · redirects: ${redirects.length} · origin: ${origin}`,
);
